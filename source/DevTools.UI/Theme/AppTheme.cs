namespace DevTools.UI.Theme;

/// <summary>
/// Application theme preference.
/// </summary>
public enum AppTheme
{
    /// <summary>
    /// Use the Light default theme.
    /// </summary>
    Light = 0,

    /// <summary>
    /// Use the Dark default theme.
    /// </summary>
    Dark = 1,

    /// <summary>
    /// Automatically sync with the host application theme.
    /// </summary>
    Auto = 2
}
